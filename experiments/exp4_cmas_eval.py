"""
experiments/exp4_cmas_eval.py — Experiment 4: evaluates CMAS for each
explanation method (integrated_gradients, ablation, both) on the trained
multimodal model's test split, and writes a Method | CMAS score table to
results/cmas_table.csv.

Requires a trained multimodal checkpoint (run exp3_multimodal.py or
train.py --mode multimodal first).
"""
from __future__ import annotations

import argparse
import csv
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import torch
import yaml
from torch.utils.data import DataLoader
from tqdm import tqdm

from dataset.dataset import FakeAVCelebDataset, collate_fn
from explainability.attribution import aggregate_cmas, explain_batch
from train import build_model, prepare_batch
from utils.seed import get_device, set_seed

# "ablation" replaced the original "attention" method name — the raw
# cross-attention weights it used to read were found during review to be
# constant regardless of input (see models/fusion.py's CrossAttentionFusion
# docstring); `explain_batch` still accepts "attention" as a backward-
# compatible alias, but new code/config should say "ablation".
METHODS = ["ablation", "integrated_gradients", "both"]


def run(config_path: str, checkpoint_path: str, max_samples: int = 200):
    with open(config_path) as f:
        cfg = yaml.safe_load(f)
    set_seed(cfg["seed"])
    device = get_device(cfg["device"]["auto_detect"])

    # weights_only=False: safe here for the same reason as evaluate.py/inference.py
    # — this checkpoint is self-generated by train.py in this same repo.
    ckpt = torch.load(checkpoint_path, map_location=device, weights_only=False)
    mode = ckpt.get("mode", "multimodal")
    if mode != "multimodal":
        raise ValueError("Experiment 4 (CMAS evaluation) requires a multimodal checkpoint.")

    model = build_model(cfg, mode, device)
    model.load_state_dict(ckpt["model_state_dict"])
    model.eval()

    ds = FakeAVCelebDataset(
        cfg["paths"]["test_manifest"],
        cache_dir=cfg["paths"]["cache_dir"],
        num_frames=cfg["model"]["num_frames"],
        sample_rate=cfg["audio"]["sample_rate"],
        max_duration_sec=cfg["audio"]["max_duration_sec"],
        split="test",
    )
    loader = DataLoader(ds, batch_size=cfg["training"]["batch_size"], shuffle=False, collate_fn=collate_fn)

    rows = []
    for method in METHODS:
        print(f"[Experiment 4] Computing CMAS with method={method}")
        all_results = []
        n_seen = 0
        for batch in tqdm(loader, desc=f"CMAS[{method}]"):
            if n_seen >= max_samples:
                break
            if batch is None:  # entire mini-batch was unreadable files — see dataset.py collate_fn
                continue
            visual_input, audio_input, labels = prepare_batch(batch, model, device, sample_rate=cfg["audio"]["sample_rate"])
            with torch.no_grad():
                visual_embed, audio_embed = model.encode(visual_input, audio_input)
                # Single source of truth for fusion/classifier branching (see
                # models/fusion.py); previously duplicated as
                # model.fusion(...) + model.classifier(...) here.
                logits = model.classify_from_embeddings(visual_embed, audio_embed)

            with torch.enable_grad():
                ve = visual_embed.clone().detach().requires_grad_(True)
                ae = audio_embed.clone().detach().requires_grad_(True)
                batch_results = explain_batch(
                    model, ve, ae, logits, labels, batch["modality_gt"].to(device),
                    batch["video_path"], method=method, ig_n_steps=cfg["explainability"]["ig_n_steps"],
                )
            all_results.extend(batch_results)
            n_seen += len(batch_results)

        summary = aggregate_cmas(all_results)
        rows.append({"method": method, **summary})
        print(f"[Experiment 4] method={method} -> mean_cmas={summary['mean_cmas']}, n={summary['n_samples']}")

    out_path = os.path.join(cfg["paths"]["results_dir"], "cmas_table.csv")
    with open(out_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["method", "mean_cmas", "std_cmas", "n_samples", "n_excluded_real"])
        writer.writeheader()
        for row in rows:
            writer.writerow(row)
    print(f"[Experiment 4] Wrote {out_path}")
    return rows


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=str, default="config.yaml")
    parser.add_argument("--checkpoint", type=str, default="checkpoints/best_model_multimodal.pt")
    parser.add_argument("--max_samples", type=int, default=200)
    args = parser.parse_args()
    run(args.config, args.checkpoint, args.max_samples)
